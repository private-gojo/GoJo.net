def forward(src, dst):
    try:
        while True:
            data = src.recv(4096)
            if not data:
                break
            dst.sendall(data)
    except:
        pass
    finally:
        try: src.close()
        except: pass
        try: dst.close()
        except: pass

def handle_client(client_sock, ip_pool, attempts):
    request = b""
    try:
        while True:
            chunk = client_sock.recv(4096)
            if not chunk:
                break
            request += chunk
            if b"\r\n\r\n" in request:
                break
    except:
        client_sock.close()
        return

    connected = False
    random.shuffle(ip_pool)

    for attempt in range(attempts):
        proxy_ip, proxy_port = ip_pool[attempt % len(ip_pool)]
        try:
            remote = socket.create_connection((proxy_ip, proxy_port), timeout=5)
            remote.sendall(request)
            response = remote.recv(4096)
            if b"200" in response or b"204" in response:
                print(f"[GOJO] Connected via {proxy_ip}:{proxy_port}")
                t1 = threading.Thread(target=forward, args=(client_sock, remote))
                t2 = threading.Thread(target=forward, args=(remote, client_sock))
                t1.daemon = True
                t2.daemon = True
                t1.start()
                t2.start()
                t1.join()
                t2.join()
                connected = True
                break
            else:
                remote.close()
        except:
            continue

    if not connected:
        try: client_sock.close()
        except: pass

def start_proxy(port, ip_pool, attempts):
    server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    server.bind(("127.0.0.1", port))
    server.listen(100)
    print(f"[GOJO] Proxy listening on 127.0.0.1:{port} | IPs loaded: {len(ip_pool)} | attempts={attempts}")

    while True:
        try:
            client, _ = server.accept()
            t = threading.Thread(target=handle_client, args=(client, ip_pool, attempts))
            t.daemon = True
            t.start()
        except KeyboardInterrupt:
            print("\n[GOJO] Shutting down...")
            break
        except:
            continue

