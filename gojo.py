PORT = 8080

# ============================================================
# PIPE LOGIC
# ============================================================

def pipe(src, dst):
    try:
        while True:
            ready, _, _ = select.select([src], [], [], 30)
            if not ready:
                break
            data = src.recv(65536)
            if not data:
                break
            dst.sendall(data)
    except:
        pass
    finally:
        try:
            src.close()
        except:
            pass
        try:
            dst.close()
        except:
            pass

# ============================================================
# CONNECTION HANDLER
# ============================================================

def handle_client(client_sock, ip_pool):
    proxy_ip = random.choice(ip_pool)

    try:
        remote = socket.create_connection((proxy_ip, PORT), timeout=10)
    except:
        try:
            client_sock.close()
        except:
            pass
        return

    print(f"[GOJO] {proxy_ip}:{PORT}")

    t1 = threading.Thread(target=pipe, args=(client_sock, remote))
    t2 = threading.Thread(target=pipe, args=(remote, client_sock))
    t1.daemon = True
    t2.daemon = True
    t1.start()
    t2.start()
    t1.join()
    t2.join()

# ============================================================
# SERVER
# ============================================================

def start_proxy(port, ip_pool):
    server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    server.bind(("127.0.0.1", port))
    server.listen(200)
    print(f"[GOJO] 127.0.0.1:{port} | pool={len(ip_pool)} | forward={PORT}")

    while True:
        try:
            client, _ = server.accept()
            t = threading.Thread(target=handle_client, args=(client, ip_pool))
            t.daemon = True
            t.start()
        except KeyboardInterrupt:
            print("\n[GOJO] Down.")
            break
        except:
            continue

# ============================================================
# MAIN
# ============================================================

def main():
    parser = argparse.ArgumentParser(description="GOJO - Pure Relay Proxy")
    parser.add_argument("-port", type=int, default=7777, help="Listen port (default: 7777)")
    args = parser.parse_args()

    ip_pool = list(ALL_IPS)

    try:
        start_proxy(args.port, ip_pool)
    except KeyboardInterrupt:
        print("\n[GOJO] Down.")
        sys.exit(0)

